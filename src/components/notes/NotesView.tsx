export function normalizeCategory(cat?: string): string {
  if (!cat || !cat.trim()) return "Quick Notes";
  const trimmed = cat.trim();
  const lower = trimmed.toLowerCase();

  // 1. Quickbooks / QBO (Must check BEFORE any "quick" check!)
  if (lower.includes("quickbook") || lower.includes("qbo")) return "Quickbooks";

  // 2. Exact match with standard default categories
  if (
    lower === "quick notes" ||
    lower === "quick note" ||
    lower === "quicknotes" ||
    lower === "quicknote" ||
    lower === "quick"
  ) {
    return "Quick Notes";
  }
  if (lower === "invoices" || lower === "invoice") return "Invoices";
  if (lower === "payments" || lower === "payment") return "Payments";
  if (lower === "payroll" || lower === "payrolls") return "Payroll";
  if (lower === "leopard") return "Leopard";
  if (lower === "paychex") return "Paychex";

  // 3. Fallback partial matching for legacy variations
  if (lower.includes("invoice")) return "Invoices";
  if (lower.includes("payment")) return "Payments";
  if (lower.includes("payroll")) return "Payroll";
  if (lower.includes("leopard")) return "Leopard";
  if (lower.includes("paychex")) return "Paychex";
  if (lower.startsWith("quick note")) return "Quick Notes";

  // 4. Return the exact category name for any custom category
  return trimmed;
}

// Checks if a note's title was auto-generated from old logic (e.g. truncated full sentence of note details)
export function isAutoGeneratedSubject(title?: string | null, content?: string | null): boolean {
  if (!title || !title.trim()) return true;
  if (!content || !content.trim()) return false;

  const tClean = title.trim();
  const cClean = content.trim();
  const lowerT = tClean.toLowerCase().replace(/\.\.\.$/, "").trim();
  const lowerC = cClean.toLowerCase();

  // Common default title placeholders
  if (["quick note", "untitled note", "note", "untitled"].includes(lowerT)) {
    return true;
  }

  // Exact match between title and content
  if (lowerT === lowerC) {
    return true;
  }

  const tWords = tClean.split(/\s+/).filter(Boolean);
  const cWords = cClean.split(/\s+/).filter(Boolean);

  // If title is already 3 or fewer words:
  // It's already a concise keyword-based subject, unless content is identical
  if (tWords.length <= 3) {
    if (cWords.length <= 3 && lowerT === lowerC) return true;
    return false;
  }

  // If title has > 3 words, it's an old raw sentence!
  // e.g. "Akash majithia - premium amount of $2965 to be deducted..."
  if (lowerC.startsWith(lowerT.substring(0, Math.min(25, lowerT.length)))) {
    return true;
  }

  // Check if 70%+ of words in title appear in content
  const firstLineWords = lowerC.split("\n")[0].split(/\s+/).filter(Boolean);
  const matchingWords = tWords.filter((w) =>
    firstLineWords.some((fw) => fw.includes(w.toLowerCase().replace(/[^a-z0-9$]/g, "")))
  );
  if (matchingWords.length / tWords.length >= 0.7) {
    return true;
  }

  return false;
}

// Focus on 3 important keywords: entity/person name + business term + amount/number (e.g. "Akash Premium $2965")
export function extractKeywordsSubject(details: string): string {
  if (!details || !details.trim()) return "Quick Note";

  const clean = details.trim();
  const lines = clean.split("\n").map((l) => l.trim()).filter(Boolean);
  const firstLine = lines.length > 1 && lines[0].length < 15 ? lines.slice(0, 2).join(" ") : (lines[0] || clean);

  // 1. Currency amount (e.g. $2965, $1,250.50, $500, 250 USD)
  const amountMatch = firstLine.match(/\$[0-9]+(?:,[0-9]{3})*(?:\.[0-9]{2})?|\b[0-9]+(?:,[0-9]{3})*(?:\.[0-9]{2})?\s*(?:usd|dollars)\b/i);
  const amount = amountMatch ? amountMatch[0] : "";

  // 2. Invoice / Reference number (e.g. Inv #402, #1092, PO-123)
  const invMatch = firstLine.match(/(?:inv(?:oice)?\.?\s*#?\s*|#)([0-9a-zA-Z-]+)/i);
  const invNum = invMatch ? (invMatch[0].startsWith("#") ? invMatch[0] : `Inv #${invMatch[1]}`) : "";

  // 3. High-priority business / finance / action terms
  const priorityKeywords = new Set([
    "premium", "deposit", "invoice", "payment", "refund", "salary", "bonus",
    "tax", "license", "reconciliation", "audit", "fee", "bill", "balance",
    "deduction", "payout", "wire", "vendor", "contract", "client", "overdue", "rates",
    "payroll", "quickbooks", "paychex", "leopard", "invoices", "payments", "uscis",
    "insurance", "reserve", "visa", "h1b", "agreement", "lease", "rent", "statement"
  ]);

  // Common stop words, prepositions, pronouns, filler words
  const stopWords = new Set([
    "a", "about", "above", "after", "again", "against", "all", "also", "am", "an", "and", "any", "are", "as", "at",
    "be", "because", "been", "before", "being", "below", "between", "both", "but", "by", "can", "check", "checked",
    "could", "did", "do", "does", "doing", "done", "down", "during", "each", "few", "for", "from", "further", "get",
    "got", "had", "has", "have", "having", "he", "her", "here", "hers", "herself", "him", "himself", "his", "how",
    "i", "if", "in", "into", "is", "it", "its", "itself", "just", "make", "making", "made", "me", "more", "most",
    "my", "myself", "need", "needs", "no", "nor", "not", "now", "of", "off", "on", "once", "only", "or", "other",
    "ought", "our", "ours", "ourselves", "out", "over", "own", "pay", "paid", "per", "please", "reminder", "note",
    "same", "send", "sent", "she", "should", "so", "some", "such", "than", "that", "the", "their", "theirs", "them",
    "themselves", "then", "there", "these", "they", "this", "those", "through", "to", "too", "under", "until", "up",
    "updated", "us", "very", "via", "was", "we", "were", "what", "when", "where", "which", "while", "who", "whom",
    "why", "will", "with", "would", "you", "your", "yours", "yourself", "yourselves", "amount", "deducted", "deduct",
    "added", "shall", "let", "see", "show", "give", "take", "taking", "tell"
  ]);

  // Clean tokens from the first line
  const rawTokens = firstLine
    .replace(/[,\/#!%^\*;:{}=\_`~()\-]/g, " ")
    .split(/\s+/)
    .map((w) => w.trim())
    .filter(Boolean);

  interface ScoredCandidate {
    word: string;
    score: number;
    originalIndex: number;
  }

  const candidates: ScoredCandidate[] = [];
  const seenLower = new Set<string>();

  // Add amount if found (highest priority)
  if (amount) {
    candidates.push({ word: amount, score: 100, originalIndex: 99 });
    seenLower.add(amount.toLowerCase());
  }

  // Add invoice number if found
  if (invNum && !seenLower.has(invNum.toLowerCase())) {
    candidates.push({ word: invNum, score: 98, originalIndex: 98 });
    seenLower.add(invNum.toLowerCase());
  }

  rawTokens.forEach((token, index) => {
    const lower = token.toLowerCase();
    if (stopWords.has(lower) || lower.length <= 1) return;
    if (amount && (token.includes("$") || token === amount.replace("$", ""))) return;
    if (invNum && token.includes(invNum.replace(/[^0-9]/g, ""))) return;
    if (/^[0-9]+$/.test(token) && !amount) return; // skip bare random numbers
    if (seenLower.has(lower)) return;
    seenLower.add(lower);

    // Format word properly: Capitalized
    const formatted =
      token.toUpperCase() === token && token.length <= 5
        ? token
        : token.charAt(0).toUpperCase() + token.slice(1).toLowerCase();

    let score = 50;
    const isCapitalized =
      token.charAt(0) === token.charAt(0).toUpperCase() && token.charAt(0) !== token.charAt(0).toLowerCase();

    if (priorityKeywords.has(lower)) {
      score = 90;
    } else if (token.toUpperCase() === token && token.length >= 2 && token.length <= 5) {
      // Acronym like USCIS, PTO, AWS
      score = 94;
    } else if (isCapitalized) {
      // Proper name / Entity like Akash, Google, Chase
      score = 92;
    } else if (token.length >= 4) {
      score = 65;
    }

    candidates.push({
      word: formatted,
      score,
      originalIndex: index,
    });
  });

  if (candidates.length === 0) {
    const fallbackWords = rawTokens.slice(0, 3).map((w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase());
    return fallbackWords.join(" ") || "Quick Note";
  }

  // Pick top 3 highest priority candidates
  const topCandidates = [...candidates]
    .sort((a, b) => b.score - a.score)
    .slice(0, 3);

  // Re-sort the chosen 3 keywords by original appearance order for natural reading flow
  topCandidates.sort((a, b) => a.originalIndex - b.originalIndex);

  return topCandidates.map((c) => c.word).join(" ");
}

export function formatFileSize(bytes: number) {
  if (!bytes || bytes === 0) return "0 B";
  const k = 1024;
  const sizes = ["B", "KB", "MB", "GB"];
  const i = Math.floor(Math.log(bytes) / Math.log(k));
  return `${parseFloat((bytes / Math.pow(k, i)).toFixed(1))} ${sizes[i]}`;
}

export function getDateUrgency(targetDateStr?: string | null, isCompleted?: boolean) {
  if (!targetDateStr) {
    return {
      status: isCompleted ? "completed" : "none",
      daysDiff: 9999,
      label: isCompleted ? "Completed" : "No deadline",
      badgeClass: isCompleted
        ? "bg-emerald-50 text-emerald-700 border-emerald-200 font-semibold"
        : "bg-slate-100 text-slate-500 border-slate-200",
      cardBorder: isCompleted ? "border-slate-200/80 bg-slate-50/60" : "border-slate-200/80 bg-white",
      highlightNotice: null,
    };
  }

  const parts = targetDateStr.split("-").map(Number);
  if (parts.length < 3 || isNaN(parts[0])) {
    return {
      status: isCompleted ? "completed" : "none",
      daysDiff: 9999,
      label: targetDateStr,
      badgeClass: isCompleted
        ? "bg-emerald-50 text-emerald-700 border-emerald-200 font-semibold"
        : "bg-slate-100 text-slate-500 border-slate-200",
      cardBorder: isCompleted ? "border-slate-200/80 bg-slate-50/60" : "border-slate-200/80 bg-white",
      highlightNotice: null,
    };
  }

  const [year, month, day] = parts;
  const targetDate = new Date(year, month - 1, day);
  const today = new Date();
  today.setHours(0, 0, 0, 0);
  targetDate.setHours(0, 0, 0, 0);

  const diffTime = targetDate.getTime() - today.getTime();
  const diffDays = Math.round(diffTime / (1000 * 60 * 60 * 24));

  const formattedDate = targetDate.toLocaleDateString("en-US", {
    month: "short",
    day: "numeric",
    year: "numeric",
  });

  // When a note is marked as completed/done:
  // Never show "Overdue by ...", never show red urgency notices!
  if (isCompleted) {
    return {
      status: "completed",
      daysDiff: 9999,
      label: formattedDate,
      badgeClass: "bg-emerald-50 text-emerald-700 border-emerald-200 font-semibold",
      cardBorder: "border-slate-200/80 bg-slate-50/70 shadow-2xs",
      highlightNotice: null,
    };
  }

  if (diffDays < 0) {
    const overdueDays = Math.abs(diffDays);
    return {
      status: "overdue",
      daysDiff: diffDays,
      label: `${formattedDate} (Overdue by ${overdueDays}d)`,
      badgeClass: "bg-rose-100 text-rose-800 border-rose-300 font-bold",
      cardBorder: "border-rose-400 bg-rose-50/40 shadow-xs ring-1 ring-rose-300/40",
      highlightNotice: `⚠️ Overdue by ${overdueDays} day${overdueDays > 1 ? "s" : ""}!`,
    };
  } else if (diffDays === 0) {
    return {
      status: "today",
      daysDiff: 0,
      label: "Due Today",
      badgeClass: "bg-amber-100 text-amber-900 border-amber-400 font-bold",
      cardBorder: "border-amber-400 bg-amber-50/50 shadow-md ring-2 ring-amber-300/40",
      highlightNotice: "⚠️ Action required today!",
    };
  } else {
    // Normal color for all other future dates (e.g. 1, 2, 3+ days) unless due today
    return {
      status: "upcoming",
      daysDiff: diffDays,
      label: diffDays === 1 ? `Due Tomorrow (${formattedDate})` : `Due in ${diffDays} days (${formattedDate})`,
      badgeClass: "bg-slate-100 text-slate-600 border-slate-200",
      cardBorder: "border-slate-200/80 bg-white hover:border-slate-300",
      highlightNotice: null,
    };
  }
}

