    setUploadProgressText(null);
    setIsCreatingCategory(false);
    setIsEditingSubject(false);
    // Only retain customSubject if user deliberately entered a custom title, NOT an old auto-generated sentence!
    const isAuto = isAutoGeneratedSubject(note.title, note.content);
    setCustomSubject(isAuto ? "" : (note.title || ""));
    setIsModalOpen(true);
